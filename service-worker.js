self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    // tolerate individual failures (e.g. a 404) so install never hard-fails
    await Promise.all(PRECACHE.map((u) => c.add(u).catch((err) => console.warn('SW skip', u, err))));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const ks = await caches.keys();
    await Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // network-first for the shell so updates propagate; offline falls back to cache
    e.respondWith(fetch(req).catch(() => caches.match('./index.html')));
    return;
  }
  // cache-first for everything else (images precached; audio fills on first play)
  e.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      const cp = res.clone();
      caches.open(CACHE).then((c) => c.put(req, cp)).catch(() => {});
      return res;
    }).catch(() => caches.match(req)))
  );
});
